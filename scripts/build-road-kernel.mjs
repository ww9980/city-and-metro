// Rebuild with rustc + the matching wasm32-unknown-unknown standard library.
import fs from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dest=path.join(root,'js/road-kernel.js');
async function inputs(){const source=await fs.readFile(path.join(root,'src-sim/road.rs')),worker=await fs.readFile(path.join(root,'src-sim/road-worker.js'),'utf8');return {source,worker,hash:createHash('sha256').update(source).update(worker).digest('hex')};}
export async function checkRoadKernel(){
  const {hash}=await inputs(),current=await fs.readFile(dest,'utf8');
  if(!current.includes('// Source SHA256: '+hash))throw Error('道路计算模块已过期，请运行 node scripts/build-road-kernel.mjs');
  const data=current.match(/const bytes='([A-Za-z0-9+/=]+)'/);
  if(!data||!WebAssembly.validate(Buffer.from(data[1],'base64')))throw Error('道路计算模块损坏');
}
function run(command,args){const r=spawnSync(command,args,{stdio:'inherit',windowsHide:true});if(r.error)throw r.error;if(r.status)throw Error(command+' failed ('+r.status+')');}
async function build(){
  const {worker,hash}=await inputs(),out=path.join(root,'src-sim/.road-kernel.wasm');
  try{
    run('rustc',['--edition=2021','--crate-type=cdylib','--target=wasm32-unknown-unknown','-C','opt-level=3','-C','lto=yes','-C','panic=abort','-C','strip=symbols',path.join(root,'src-sim/road.rs'),'-o',out]);
    const bytes=await fs.readFile(out);
    await fs.writeFile(dest,"'use strict';\n// Generated by scripts/build-road-kernel.mjs; do not edit.\n// Source SHA256: "+hash+"\n(function(CM){\nconst bytes='"+bytes.toString('base64')+"';\nlet module=null;try{module=new WebAssembly.Module(Uint8Array.from(atob(bytes),c=>c.charCodeAt(0)));}catch(e){/* JavaScript fallback. */}\n"+worker+"\nCM.RoadKernel={module,worker:roadKernelWorker};\n})(window.CM);\n");
    console.log('Built exact road kernel: '+bytes.length+' bytes');
  }finally{await fs.unlink(out).catch(()=>{});}
}
async function test(){
  const out=path.join(root,'src-sim/.road-kernel-tests-'+process.pid+'.exe');
  try{run('rustc',['--edition=2021','--test',path.join(root,'src-sim/road.rs'),'-o',out]);run(out,[]);}
  finally{await fs.unlink(out).catch(()=>{});await fs.unlink(out.replace(/\.exe$/,'.pdb')).catch(()=>{});}
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  if(process.argv.includes('--check')){await checkRoadKernel();console.log('道路计算模块与源码一致');}
  else if(process.argv.includes('--test'))await test();
  else await build();
}
